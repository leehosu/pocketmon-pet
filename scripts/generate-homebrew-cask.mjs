// AI-GENERATED: 릴리스 DMG의 버전·SHA-256으로 leehosu/homebrew-tap용 Cask를 생성한다.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const [versionInput, dmgInput, outputInput] = process.argv.slice(2);
if (!versionInput || !dmgInput || !outputInput) {
  throw new Error('Usage: node scripts/generate-homebrew-cask.mjs <version> <dmg> <output>');
}

const version = versionInput.replace(/^v/, '');
if (!/^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(version)) {
  throw new Error(`Invalid semantic version: ${versionInput}`);
}
const dmgPath = resolve(repoRoot, dmgInput);
const outputPath = resolve(repoRoot, outputInput);
const sha256 = createHash('sha256').update(readFileSync(dmgPath)).digest('hex');
const cask = `# typed: false
# frozen_string_literal: true

# This file is generated by pocketmon-pet. Do not edit manually.
cask "pocketmon-pet" do
  version "${version}"
  sha256 "${sha256}"

  url "https://github.com/leehosu/pocketmon-pet/releases/download/v#{version}/Pocketmon-Pet-#{version}-universal.dmg"
  name "Pocketmon Pet"
  desc "Pokemon Gold-style desktop pet that grows while you code"
  homepage "https://github.com/leehosu/pocketmon-pet"

  app "Pocketmon Pet.app"

  zap trash: "~/.pocketmon"
end
`;

writeFileSync(outputPath, cask);
console.log(`Generated ${outputPath}`);
